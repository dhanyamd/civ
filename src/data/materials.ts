const BY_ID = new Map(MATERIALS.map((m) => [m.id, m]));

export function material(id: string): MaterialSpec {
  const found = BY_ID.get(id);
  if (!found) throw new Error(`Unknown material id: ${id}`);
  return found;
}

export function maybeMaterial(id: string): MaterialSpec | undefined {
  return BY_ID.get(id);
}

/** Materials that can legitimately take on a given structural role. */
export function materialsForRole(role: ElementRole): MaterialSpec[] {
  return MATERIALS.filter((m) => m.roles.includes(role));
}

/** Carbon intensity band for the badge on a material chip. */
export type ImpactBand = 'very-high' | 'high' | 'moderate' | 'low' | 'very-low';

export function impactBand(m: MaterialSpec): ImpactBand {
  const perKg = m.carbonPerKg;
  if (perKg >= 5) return 'very-high';
  if (perKg >= 1.5) return 'high';
  if (perKg >= 0.4) return 'moderate';
  if (perKg >= 0.1) return 'low';
  return 'very-low';
}

