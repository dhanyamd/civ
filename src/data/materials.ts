/**
 * Overlay the imported EPDs onto the catalogue.
 *
 * Where a published EPD exists it wins outright: its GWP-fossil A1–A3, its
 * biogenic figure and its gross density replace whatever was written here, and
 * the material is marked `epd` so the UI can link to the source document.
 *
 * Where no EPD matched, the figure stays as an industry estimate and is
 * labelled as one. That distinction is shown to the user rather than smoothed
 * over — a number you cannot trace is worth less than one you can, and
 * pretending otherwise is the failure mode this whole import exists to fix.
 *
 * Regenerate with: node scripts/fetch-epds.mjs
 */
const EPD_BY_MATERIAL = new Map(
  (epdData.records as EpdRecord[]).map((record) => [record.materialId, record]),
);

for (const spec of MATERIALS) {
  const epd = EPD_BY_MATERIAL.get(spec.id);
  if (!epd) {
    spec.dataQuality = 'estimate';
    spec.source = `${spec.source} — industry estimate, no matching EPD found in Ökobaudat`;
    continue;
  }

  spec.dataQuality = 'epd';
  spec.epd = epd;
  spec.carbonPerKg = epd.carbonPerKg;
  if (epd.biogenicPerKg != null && epd.biogenicPerKg !== 0) {
    spec.biogenicPerKg = epd.biogenicPerKg;
  }
  // The EPD's own declared density is more trustworthy than a textbook value,
  // and keeping them consistent is what makes the mass arithmetic hold up.
  if (epd.densityKgM3 && epd.densityKgM3 > 10) {
    spec.densityKgM3 = epd.densityKgM3;
  }
  spec.source = `Ökobaudat EPD — ${epd.epdName}`;
}

